-- Run once in SQL*Plus / SQL Developer as the app user (NOT SYSTEM) when
-- backend = "oracle". Needs Oracle 12c+ (XE 18c/21c are fine).
-- NIC_CODES is filled from final_k/NIC_5digit.csv automatically on first start.
--
-- If you have the old tables from the previous version, drop them first:
--   DROP TABLE NIC_CODES; DROP TABLE RESULT_CODES; DROP TABLE CONTACT_INFO;
--   DROP TABLE LOGIN_DETAILS; DROP SEQUENCE SEQ_LOGIN_DETAILS_ID;

CREATE TABLE NIC_CODES (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NIC_CODE      VARCHAR2(5)   NOT NULL UNIQUE,
    ACTIVITY_NAME VARCHAR2(100),
    DESCRIPTION   VARCHAR2(500) NOT NULL
);

CREATE TABLE RESULT_CODES (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACTIVITY_NAME VARCHAR2(2000) NOT NULL,
    DESCRIPTION   VARCHAR2(2000),
    PREDICTED_NIC VARCHAR2(4000),
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE CONTACT_INFO (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    YOUR_NAME     VARCHAR2(100)  NOT NULL,
    YOUR_MAIL     VARCHAR2(200)  NOT NULL,
    YOUR_FEEDBACK VARCHAR2(2000) NOT NULL,
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP
);
